// The at-rest key for calendar credentials, made available WITHOUT a restart.
//
// The guided Google Calendar setup (Settings > Integrations) stores the OAuth client
// secret encrypted (calendar-secret.ts). A keyless local install has no key to encrypt it
// under, and "set KP_SECRET, then restart" is exactly the step the guided flow removes. So
// on the save path, when no key is set, this module:
//
//   1. adopts a KP_CALENDAR_SECRET_KEY already written to .env.local (a save that ran
//      before this process started, or one the owner typed in), else
//   2. generates 32 random bytes and APPENDS them to .env.local — the gitignored file
//      `next dev` / `next start` load at boot, so the next start reads the same key — and
//   3. sets it in the running process, so this save and the OAuth callback that follows
//      seconds later both work now.
//
// What it never does:
//   - overwrite a value. A non-empty KP_CALENDAR_SECRET_KEY in the file is adopted, never
//     replaced; only an EMPTY placeholder line (`KP_CALENDAR_SECRET_KEY=`) is filled in.
//   - touch KP_SECRET. That key also signs sessions and edge requests; generating it would
//     change the auth posture of an install whose owner only asked for a calendar.
//   - set a key it could not persist. A key that lives only in memory seals a secret that
//     the next restart cannot open, so a failed write refuses the save instead.
//   - log the key. The only thing written anywhere is the file line itself.

import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { calendarSecretKeyConfigured } from "./calendar-secret";

export const CALENDAR_KEY_ENV = "KP_CALENDAR_SECRET_KEY";

export type CalendarKeyOutcome =
  /** A key was already set in this process (KP_CALENDAR_SECRET_KEY or KP_SECRET). */
  | { ok: true; source: "env" }
  /** .env.local already carried one; it is now set in this process too. */
  | { ok: true; source: "file" }
  /** A fresh key was written to .env.local and set in this process. */
  | { ok: true; source: "generated" }
  /** No key, and none could be persisted. Nothing was set. */
  | { ok: false; reason: "persist_failed" };

const LINE = new RegExp(`^\\s*(?:export\\s+)?${CALENDAR_KEY_ENV}\\s*=(.*)$`);

function unquote(raw: string): string {
  const v = raw.trim();
  if (v.length >= 2 && (v[0] === '"' || v[0] === "'") && v[v.length - 1] === v[0]) return v.slice(1, -1).trim();
  return v;
}

/** The file .env.local lives in: the launch directory, which is where Next loads it from. */
export function defaultEnvLocalPath(): string {
  return path.join(process.cwd(), ".env.local");
}

export function ensureCalendarSecretKey(
  opts: { env?: Record<string, string | undefined>; envFile?: string; generate?: () => string } = {}
): CalendarKeyOutcome {
  const env = opts.env ?? process.env;
  if (calendarSecretKeyConfigured(env)) return { ok: true, source: "env" };

  const file = opts.envFile ?? defaultEnvLocalPath();
  let text = "";
  // One read, no separate existence check: a check-then-write leaves a window in which
  // another process creates the file and this write replaces it (CodeQL js/file-system-race).
  let existed = true;
  try {
    text = readFileSync(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code === "ENOENT") existed = false;
    // An unreadable file is one we must not rewrite either: we cannot know what it holds.
    else return { ok: false, reason: "persist_failed" };
  }

  const lines = text.split(/\r?\n/);
  let placeholderAt = -1;
  for (let i = 0; i < lines.length; i++) {
    const m = LINE.exec(lines[i]);
    if (!m) continue;
    const value = unquote(m[1]);
    if (value) {
      env[CALENDAR_KEY_ENV] = value;
      return { ok: true, source: "file" };
    }
    if (placeholderAt < 0) placeholderAt = i;
  }

  const key = (opts.generate ?? (() => randomBytes(32).toString("base64url")))();
  const assignment = `${CALENDAR_KEY_ENV}=${key}`;
  let next: string;
  if (placeholderAt >= 0) {
    lines[placeholderAt] = assignment;
    next = lines.join(text.includes("\r\n") ? "\r\n" : "\n");
  } else {
    const eol = text.includes("\r\n") ? "\r\n" : "\n";
    const sep = text === "" || text.endsWith("\n") ? "" : eol;
    next =
      text +
      sep +
      `# Generated by the Google Calendar setup in Settings > Integrations: seals the stored${eol}` +
      `# OAuth client secret at rest. Keep it; changing it makes the stored secret unreadable.${eol}` +
      assignment +
      eol;
  }
  try {
    // A file that did not exist is created exclusively ("wx"), so a file another process
    // made since our read is never overwritten.
    writeFileSync(file, next, { encoding: "utf8", mode: 0o600, flag: existed ? "w" : "wx" });
  } catch (error) {
    // Lost the creation race: the file exists now, so read it again (it may carry a key).
    if (!existed && (error as NodeJS.ErrnoException)?.code === "EEXIST") return ensureCalendarSecretKey(opts);
    return { ok: false, reason: "persist_failed" };
  }
  env[CALENDAR_KEY_ENV] = key;
  return { ok: true, source: "generated" };
}
